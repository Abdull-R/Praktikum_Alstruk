# Praktikum 5 - Struktur Data Dasar

nilai = [78, 85, 90, 85]
mahasiswa = {"nama": "Nadia", "kelas": "IF-A"}
koordinat = (5, 8)
angka = (2, 4, 4, 6, 8)

# 1. Menampilkan nilai pertama dari list
print("Nilai pertama:", nilai[0])

# 2. Menambahkan nilai 95 ke list
nilai.append(95)
print("List nilai terbaru:", nilai)

# 3. Menampilkan nama mahasiswa
print("Nama mahasiswa:", mahasiswa["nama"])

# 4. Menampilkan koordinat pertama
print("Koordinat pertama:", koordinat[0])

# 5. Menampilkan angka secara berurutan
print("Angka terurut:", sorted(angka))

# Menampilkan angka unik
print("Angka unik:", sorted(set(angka)))

# 6. Menjelaskan penggunaan set
print("Set angka:", set(angka))