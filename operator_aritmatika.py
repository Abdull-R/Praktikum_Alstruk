# Praktikum 2 - Operator Aritmatika

harga = 12500
jumlah = 4

# Menghitung total harga
total_harga = harga * jumlah

# Menghitung sisa pembagian dengan 2.000
sisa_pembagian = total_harga % 2000

# Menghitung harga setelah diskon
diskon = 5000
harga_setelah_diskon = total_harga - diskon

# Menampilkan hasil
print("Harga per buku: Rp", harga)
print("Jumlah buku:", jumlah)
print("Total harga: Rp", total_harga)
print("Sisa pembagian total harga dengan 2.000:", sisa_pembagian)
print("Diskon: Rp", diskon)
print("Harga setelah diskon: Rp", harga_setelah_diskon)