# Praktikum 4 - Operator Penugasan

poin = 100
print("1. Nilai awal:", poin)

poin += 25
print("2. Setelah poin += 25:", poin)

poin -= 10
print("3. Setelah poin -= 10:", poin)

poin *= 2
print("4. Setelah poin *= 2:", poin)

poin /= 2
print("5. Setelah poin /= 2:", poin)