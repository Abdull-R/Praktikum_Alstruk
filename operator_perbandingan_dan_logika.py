# Praktikum 3 - Operator Perbandingan dan Logika

nilai = 82
kehadiran = 90

# Memeriksa masing-masing syarat
syarat_nilai = nilai >= 75
syarat_kehadiran = kehadiran >= 80

print("Nilai:", nilai)
print("Kehadiran:", str(kehadiran) + "%")
print("Memenuhi syarat nilai:", syarat_nilai)
print("Memenuhi syarat kehadiran:", syarat_kehadiran)

# Kedua syarat harus terpenuhi
lulus_and = syarat_nilai and syarat_kehadiran
print("Lulus menggunakan and:", lulus_and)

# Mengubah nilai menjadi 70
nilai = 70
syarat_nilai = nilai >= 75

print("\nNilai setelah diubah:", nilai)
print("Memenuhi syarat nilai:", syarat_nilai)
print("Lulus menggunakan and:",
      syarat_nilai and syarat_kehadiran)

# Menggunakan or
print("Lulus menggunakan or:",
      syarat_nilai or syarat_kehadiran)